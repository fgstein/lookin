"""A Markdown (.md) rendering of the same report `report.py` writes as HTML.

For a report that goes where Markdown is read: a wiki, a merge request, a
notebook, a folder of notes. `MarkdownReport` subclasses `Report` and
overrides its content methods, so report_builder.py builds it unchanged
(as for report_pptx.py).

One file, like the HTML report: every chart is embedded as a base64 PNG
data URI, so nothing beside it has to travel with it -- and nothing is
fetched when it is opened (see CLAUDE.md). Most Markdown viewers show
those images; a few (some wikis) do not, and show the caption instead.
"""
from __future__ import annotations

import base64
import io
import platform
from datetime import datetime

from lookin.core import markdown_lite as md
from lookin.core.report import Report, _fmt


def _cell(value) -> str:
    text = value if isinstance(value, str) else _fmt(value)
    return md.escape(str(text)).replace("|", "\\|").replace("\n", " ")


class MarkdownReport(Report):
    """Same content-building API as `Report`; renders Markdown, not HTML."""

    extension = "md"
    mime = "text/markdown; charset=utf-8"

    @staticmethod
    def tiles(items: list) -> str:
        return "\n".join(f"- **{md.escape(label)}**: {value if isinstance(value, str) else _fmt(value)}"
                         for label, value, _cls in items)

    @staticmethod
    def table(headers: list, rows: list, note: str = "") -> str:
        head = "| " + " | ".join(_cell(h) for h in headers) + " |"
        rule = "|" + "|".join(" --- " if i == 0 else " ---: " for i in range(len(headers))) + "|"
        body = ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
        out = "\n".join([head, rule, *body])
        return out + (f"\n\n*{md.escape(note)}*" if note else "")

    @staticmethod
    def dataframe(df, note: str = "", float_digits: int = 4) -> str:
        headers = [str(df.index.name or "")] + [str(c) for c in df.columns]
        rows = [[str(idx)] + [df.loc[idx, c] for c in df.columns] for idx in df.index]
        return MarkdownReport.table(headers, rows, note)

    @staticmethod
    def figure(fig, caption: str = "", dpi: int = 130) -> str:
        import matplotlib.pyplot as plt

        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=dpi, bbox_inches="tight")
        plt.close(fig)
        encoded = base64.b64encode(buf.getvalue()).decode("ascii")
        alt = md.escape(caption or "chart").replace("\n", " ")
        return f"![{alt}](data:image/png;base64,{encoded})" + (f"\n\n*{md.escape(caption)}*" if caption else "")

    @staticmethod
    def paragraph(text: str, note: bool = False) -> str:
        return f"*{md.escape(text)}*" if note else md.escape(text)

    @staticmethod
    def notes(markdown: str) -> str:
        return md.for_report(markdown).strip()

    def to_markdown(self) -> str:
        parts = [f"# {md.escape(self.title)}", ""]
        if self.subtitle:
            parts += [md.escape(self.subtitle), ""]
        if self.meta:
            parts += [self.table(["", ""], [[k, str(v)] for k, v in self.meta]).replace("| --- | ---: |", "| --- | --- |"), ""]
        for section in self.sections:
            parts += [f"## {md.escape(section.title)}", ""]
            for block in section.blocks:
                if block:
                    parts += [block, ""]
        generated = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        parts += ["---", "", f"*Generated by Lookin on {generated} ({md.escape(platform.node())}). Self-contained: "
                             "every image is embedded, nothing is fetched when this file is opened.*", ""]
        return "\n".join(parts)

    def to_bytes(self) -> bytes:
        return self.to_markdown().encode("utf-8")
